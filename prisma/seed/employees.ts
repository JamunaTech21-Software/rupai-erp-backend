const d = (v: string) => new Date(`${v}T00:00:00.000Z`);

export async function seedEmployees(db: Database, userId: string): Promise<number> {
  for (const [i, p] of PEOPLE.entries()) {
    const [
      employeeId,
      title,
      firstName,
      lastName,
      gender,
      department,
      designation,
      employeeType,
      status,
      joined,
      grade,
      basic,
    ] = p;
    const n = String(i + 1).padStart(2, '0');
    const houseRent = basic * 0.5;
    const medicalAllowance = 1500;
    const conveyance = 1000;
    await seedOne(
      db,
      userId,
      'employee',
      { employeeId },
      {
        employeeId,
        employeeType,
        title,
        firstName,
        middleName: null,
        lastName,
        fatherName: `Father of ${firstName}`,
        motherName: `Mother of ${firstName}`,
        dateOfBirth: d(`${1975 + i * 2}-0${(i % 9) + 1}-15`),
        gender,
        bloodGroup: 'b-positive',
        maritalStatus: i % 3 ? 'married' : 'single',
        nationality: 'bangladeshi',
        religion: 'islam',
        tinNo: null,
        nationalIdNo: `19900000000000${n}`,
        passportNo: null,
        drivingLicenseNo: null,
        department,
        designation,
        jobGrade: grade,
        employmentDate: d(joined),
        probationEndDate: null,
        confirmationDate: null,
        employmentType: 'full-time',
        workingLocation:
          department === 'estate' || department === 'operations' ? 'jamuna-tea-estate' : 'head-office',
        jobNature: department === 'operations' ? 'operational' : 'administrative',
        reportingTo: designation === 'manager' ? 'department-head' : 'estate-manager',
        numberOfDependents: i % 4,
        employeeStatus: status,
        mobileNo: `+88017110000${n}`,
        email: `${firstName.toLowerCase().replace(/[^a-z]/g, '')}.${lastName.toLowerCase()}@example.com`,
        personalEmail: null,
        presentAddress: 'Sreemangal, Moulvibazar',
        permanentAddress: 'Sreemangal, Moulvibazar',
        sameAsPermanentAddress: true,
        district: 'moulvibazar',
        upazila: 'sreemangal',
        postalCode: '3210',
        basicSalary: basic,
        houseRent,
        medicalAllowance,
        conveyance,
        otherAllowance: null,
        totalSalary: basic + houseRent + medicalAllowance + conveyance,
        paymentMethod: 'bank',
        bankName: 'dbbl',
        accountNo: `1011100${n}`,
        remarks: null,
        emergencyContactName: `Spouse of ${firstName}`,
        emergencyRelation: 'spouse',
        emergencyMobile: `+88018110000${n}`,
        emergencyAlternateMobile: null,
        emergencyAddress: null,
        nomineeName: `Spouse of ${firstName}`,
        nomineeRelation: 'spouse',
        nomineeDateOfBirth: null,
        nomineeNationalId: null,
        nomineeMobile: null,
        nomineeAddress: null,
      },
    );
  }
  return PEOPLE.length;
}
